class TextAnalyzerError(Exception):
    """
    @brief Базова помилка аналізатора текстів.

    Використовується як спільний батьківський клас для помилок,
    пов'язаних з обробкою текстових файлів.
    """
    pass


class InvalidTextInputError(TextAnalyzerError):
    """
    @brief Помилка некоректних вхідних даних.

    Виникає, якщо файл не існує, шлях не є файлом
    або файл має неправильне розширення.
    """
    pass
